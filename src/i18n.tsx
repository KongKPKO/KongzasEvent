type TranslationKey = keyof typeof translations.en;

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
  dateLocale: string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const getInitialLanguage = (): Language => {
  if (typeof window === 'undefined') return 'en';
  const saved = window.localStorage.getItem(STORAGE_KEY);
  return saved === 'th' ? 'th' : 'en';
};

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(STORAGE_KEY, nextLanguage);
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
    applyLegacyLocalization(language);
    const observer = new MutationObserver(() => {
      window.requestAnimationFrame(() => applyLegacyLocalization(language));
    });
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['placeholder', 'aria-label', 'title'],
    });
    return () => observer.disconnect();
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    const t = (key: TranslationKey, vars?: Record<string, string | number>) => {
      const raw = String(translations[language][key] || translations.en[key] || key);
      if (!vars) return raw;
      return Object.entries(vars).reduce(
        (text, [name, replacement]) => text.split(`{${name}}`).join(String(replacement)),
        raw
      );
    };

    return {
      language,
      setLanguage,
      toggleLanguage: () => setLanguage(language === 'en' ? 'th' : 'en'),
      t,
      dateLocale: language === 'th' ? 'th-TH' : 'en',
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used inside LanguageProvider');
  }
  return context;
}

export function LanguageToggle({ className = '' }: { className?: string }) {
  const { language, toggleLanguage, t } = useI18n();
  const nextLanguage = language === 'en' ? 'TH' : 'EN';

  return (
    <button
      type="button"
      onClick={toggleLanguage}
      className={`inline-flex items-center rounded-full border border-pink-200 bg-white px-3 py-2 text-xs font-black text-pink-700 shadow-sm transition hover:bg-pink-50 ${className}`}
      aria-label={t('switchLanguage')}
    >
      {nextLanguage}
    </button>
  );
}
